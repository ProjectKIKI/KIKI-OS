#!/usr/bin/env python3
"""Plan and assemble an independently auditable native GNOME candidate root."""
import argparse
import json
from pathlib import Path
import re
import shutil
import subprocess
import ki2sessioncandidate as c
from ki2stage3candidate import read_manifest

DESKTOP=['gnome-shell','gnome-session','gdm','kiki-gdm-integration','kiki-session-integration','glibc-locales','python3-argcomplete','librsvg','gnome-settings-daemon-schemas','adwaita-icon-theme','hicolor-icon-theme','kiki-desktop-fonts','kiki-mesa-bootstrap']

def plan():
    records={r['name']:dict(r,file=str(c.BASE/'packages/x86_64'/r['file'])) for r in json.loads((c.BASE/'snapshot.json').read_text())['packages']}
    for f in (c.TARGET/'validation').glob('*-build.json'):
        r=json.loads(f.read_text())
        if r.get('file'):records[r['name']]=r
    source=(c.REPO/'tools/ki2bootiso.py').read_text()
    section=source.split('static void select_server_core_packages(')[1].split('NULL,')[0]
    server=re.findall(r'"([a-z0-9][a-z0-9-]+)"',section.split('defaults[] = {')[1])
    roots=sorted(set(server+DESKTOP)-{'kiki-installer-tui'})
    if 'kiki-gnome-desktop' in records:roots.append('kiki-gnome-desktop')
    manifests={};order=[];active=[];errors=[]
    def visit(name):
        if name in order:return
        if name in active:
            errors.append(dict(reason='Runtime cycle',cycle=active+[name]));return
        if name not in records:
            errors.append(dict(reason='Missing supplier',name=name));return
        if name not in manifests:
            r=records[name]
            if c.sha256_file(r['file'])!=r['sha256']:raise ValueError('Package SHA mismatch: '+name)
            manifests[name]=read_manifest(Path(r['file']))
        active.append(name)
        for dep in manifests[name].get('dependencies',{}).get('runtime',[]):visit(dep)
        active.pop();order.append(name)
    for name in roots:visit(name)
    owners={};conflicts=[]
    for name in order:
        for f in manifests[name]['files']:
            if f['type']=='dir':continue
            path=f['path']
            if path in owners:conflicts.append(dict(path=path,owners=[owners[path],name]))
            else:owners[path]=name
    result=dict(roots=roots,order=order,packages=[records[n] for n in order],errors=errors,conflicts=conflicts,installer_bundle_in_target=any(n in order for n in ['kiki-installer-gtk','kiki-kmscon','kiki-x11-runtime']))
    c.save(c.TARGET/'validation/desktop-root-plan.json',result)
    print('Root plan:',len(order),'packages;',len(errors),'dependency errors;',len(conflicts),'file conflicts',flush=True)
    return result

def assemble(result,dest,prior=None):
    if result['errors'] or result['conflicts']:raise ValueError('Resolve root plan errors before assembly')
    if not dest.resolve().is_relative_to(c.WORK.resolve()):raise ValueError('Root outside candidate work')
    old={}
    if prior:
        if dest.exists() and prior!=dest:raise FileExistsError(dest)
        if not prior.resolve().is_relative_to(c.WORK.resolve()):raise ValueError('Prior root outside candidate work')
        oldreport=json.loads((c.TARGET/'validation/desktop-root-assembled.json').read_text())
        if str(prior)!=oldreport['root']:raise ValueError('Prior assembled root report mismatch')
        old={r['name']:r for r in oldreport['packages']}
        if prior!=dest:subprocess.run(['cp','-a','--reflink=auto',str(prior),str(dest)],check=True)
    else:dest.mkdir(exist_ok=False)
    for r in result['packages']:
        if r['name'] in old and old[r['name']]['sha256']==r['sha256']:continue
        c.build.extract_package_rootfs(Path(r['file']),dest)
        print('Extracted',r['name'],flush=True)
    subprocess.run(['/usr/sbin/chroot',str(dest),'/sbin/ldconfig'],check=True)
    verify(result,dest)

def verify(result,dest):
    generated=[]
    for r in result['packages']:
        for f in read_manifest(Path(r['file']))['files']:
            p=dest/f['path'].lstrip('/')
            if f['path']=='/etc/ld.so.cache':
                if not p.is_file():raise ValueError('Missing generated loader cache')
                generated.append(dict(path=f['path'],sha256=c.sha256_file(p),reason='Regenerated by target ldconfig'))
                continue
            if f['type']=='file' and (not p.is_file() or c.sha256_file(p)!=f['sha256']):raise ValueError('Assembled payload mismatch: '+f['path'])
    c.save(c.TARGET/'validation/desktop-root-assembled.json',dict(root=str(dest),packages=result['packages'],sha256_checked=True,generated_caches=generated,ownership_conflicts=0,installer_bundle_in_target=False))
    print('Verified clean root payload SHA and regenerated caches',flush=True)

if __name__=='__main__':
    p=argparse.ArgumentParser();p.add_argument('--assemble',type=Path);p.add_argument('--from-root',type=Path);p.add_argument('--verify-root',type=Path);p.add_argument('--update-root',type=Path);a=p.parse_args()
    result=plan()
    if a.assemble:assemble(result,a.assemble,a.from_root)
    if a.update_root:assemble(result,a.update_root,a.update_root)
    if a.verify_root:
        if not a.verify_root.resolve().is_relative_to(c.WORK.resolve()):raise ValueError('Root outside candidate work')
        verify(result,a.verify_root)
